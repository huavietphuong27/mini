import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const contractPath = path.join(ROOT, 'contracts', 'DocumentTimestampRegistry.sol');
const source = fs.readFileSync(contractPath, 'utf8');

const input = {
  language: 'Solidity',
  sources: {
    'DocumentTimestampRegistry.sol': {
      content: source,
    },
  },
  settings: {
    optimizer: {
      enabled: true,
      runs: 200,
    },
    evmVersion: 'paris',
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'],
      },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));

if (output.errors && output.errors.length > 0) {
  const errors = output.errors.filter((e) => e.severity === 'error');
  const warnings = output.errors.filter((e) => e.severity !== 'error');
  for (const w of warnings) {
    console.warn('[WARN]', w.formattedMessage);
  }
  if (errors.length > 0) {
    for (const err of errors) {
      console.error('[ERROR]', err.formattedMessage);
    }
    process.exit(1);
  }
}

const compiled = output.contracts['DocumentTimestampRegistry.sol']['DocumentTimestampRegistry'];
const abi = compiled.abi;
const bytecode = '0x' + compiled.evm.bytecode.object;

fs.mkdirSync(path.join(ROOT, 'artifacts'), { recursive: true });
const artifact = {
  contractName: 'DocumentTimestampRegistry',
  compilerVersion: solc.version(),
  evmVersion: 'paris',
  abi,
  bytecode,
};

fs.writeFileSync(
  path.join(ROOT, 'artifacts', 'DocumentTimestampRegistry.json'),
  JSON.stringify(artifact, null, 2) + '\n',
  'utf8'
);

const frontendConfig = `// Auto-generated by scripts/compile.mjs
window.CONTRACT_CONFIG = ${JSON.stringify(
  {
    contractName: 'DocumentTimestampRegistry',
    compilerVersion: solc.version(),
    defaultRpcUrl: 'http://127.0.0.1:7545',
    abi,
    bytecode,
  },
  null,
  2
)};
`;

fs.mkdirSync(path.join(ROOT, 'frontend'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'frontend', 'contract-config.js'), frontendConfig, 'utf8');

console.log('Compiled DocumentTimestampRegistry.sol successfully.');
console.log('Compiler:', solc.version());
console.log('Artifact:', path.join(ROOT, 'artifacts', 'DocumentTimestampRegistry.json'));
console.log('Frontend config:', path.join(ROOT, 'frontend', 'contract-config.js'));
